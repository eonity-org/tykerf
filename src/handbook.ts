// The handbook: a page's system on one page, generated from the page as it is now, so it is never out
// of date. The theme (colours as swatches, fonts as specimens, lengths as bars), then every block in
// tree order with what names it (its name, its path, its #sw- link: chips to copy into a request)
// and its tasks, the open ones and the ones that are done with their reply (what was decided).
// The editor serves it at /_tykerf/handbook (HTML, for people) and /_tykerf/handbook.md (for agents).

import { KIND_WORD, type Node, isOp, walk } from './model.js';
import { pathOf } from './refs.js';
import { readOverrides, readTheme } from './library.js';
import { type TaskNow, sayTask, tasks } from './tasks.js';
import type { Workspace } from './workspace.js';

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);

/** The theme values the page uses: the site's shared theme, the page's own theme over it, then its own values. */
export function pageTheme(ws: Workspace): Record<string, string> {
  return { ...readTheme(ws.siteHead()), ...readTheme(ws.head()), ...readOverrides(ws.head()) };
}

type Kind = 'colour' | 'font' | 'size' | 'length' | 'other';
const kindOf = (name: string): Kind =>
  name.startsWith('--color') ? 'colour'
    : name.startsWith('--font') ? 'font'
      : name.startsWith('--text') ? 'size'
        : /^--(radius|gap|space|max-width)/.test(name) ? 'length' : 'other';

/** The first words of a box, as a reader sees them. */
function firstWords(code: string | null, n = 140): string {
  const text = (code ?? '')
    .replace(/<(style|script|template)\b[\s\S]*?<\/\1>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim();
  return text.length > n ? `${text.slice(0, n - 1)}…` : text;
}

interface Entry { node: Node; depth: number; path: string; words: string; tasks: TaskNow[] }

function entries(ws: Workspace): Entry[] {
  const layout = ws.load();
  const all = tasks(ws);
  const depth = new Map<string, number>();
  const out: Entry[] = [];
  walk(layout.root, (n, parent) => {
    if (n.type === 'empty') return;
    depth.set(n.id, parent ? depth.get(parent.id)! + 1 : 0);
    out.push({
      node: n, depth: depth.get(n.id)!, path: pathOf(layout, n.id),
      words: n.type === 'leaf' ? firstWords(ws.content(n.id)) : '',
      // open tasks first, then the ones that are done
      tasks: all.filter((x) => x.block === n.id).sort((a, b) => Number(!!a.done) - Number(!!b.done) || a.n - b.n),
    });
  });
  return out;
}

const kindWord = (n: Node) => (isOp(n) ? `${KIND_WORD[n.kind]} of ${n.children.length}` : 'box');
const tagsOf = (n: Node) => (n.type === 'empty' ? [] : n.tags);
const typeOf = (n: Node) => (n.type === 'empty' ? undefined : n.boxType);

/** The handbook as Markdown, for an agent or a colleague: the theme values, then the blocks with their tasks. */
export function handbookMarkdown(ws: Workspace, name: string): string {
  const theme = Object.entries(pageTheme(ws));
  const lines = [`# Handbook: ${name}`, '', 'Generated by TYKERF from the page as it is now.', ''];
  if (theme.length) {
    lines.push('## Theme', '', 'CSS variables every block uses; use them instead of fixed values.', '');
    for (const [n, v] of theme) lines.push(`- \`${n}\`: \`${v}\``);
    lines.push('');
  }
  lines.push('## Blocks', '', 'In page order. Refer to a block by its name or path; link to it with #sw-<name>.', '');
  for (const e of entries(ws)) {
    const extra = [typeOf(e.node) && `type ${typeOf(e.node)}`, tagsOf(e.node).length && `tags ${tagsOf(e.node).map((t) => `#${t}`).join(' ')}`].filter(Boolean).join(', ');
    lines.push(`${'  '.repeat(e.depth)}- **${e.node.id}** (${kindWord(e.node)}${extra ? `; ${extra}` : ''}) \`${e.path}\`${e.words ? `: ${e.words}` : ''}`);
    for (const x of e.tasks) lines.push(`${'  '.repeat(e.depth + 1)}- task ${sayTask(x)}`);
  }
  return `${lines.join('\n')}\n`;
}

