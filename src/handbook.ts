// the TYKERF mark, as the editor draws it (cell 4, amber, is the block in focus)
const MARK = '<svg class="mark" viewBox="0 0 64 64" aria-hidden="true"><rect width="64" height="20" rx="6"/><rect y="27" width="28.5" height="37" rx="6"/><rect class="focus" x="35.5" y="27" width="28.5" height="12" rx="3"/><rect x="35.5" y="45" width="11.25" height="19" rx="3"/><rect x="52.75" y="45" width="11.25" height="19" rx="3"/></svg>';

const copy = (text: string, label = text) => `<button class="copy" data-copy="${esc(text)}" title="Copy">${esc(label)}</button>`;

/** The @font-face rules of the page's heads, so the specimens show the page's own fonts. */
const fontFaces = (ws: Workspace) => [...(ws.siteHead() + ws.head()).matchAll(/@font-face\s*\{[^}]*\}/g)].map((m) => m[0]).join('\n');

/** The handbook as a page for people. `base` is where the page's own files are, relative to the handbook's address. */
export function handbookPage(ws: Workspace, name: string, base = '../'): string {
  const theme = pageTheme(ws);
  const vars = Object.entries(theme);
  const of = (k: Kind) => vars.filter(([n]) => kindOf(n) === k);
  // theme values can refer to each other (color-mix(…var(--color-bg)…)): they are all declared, then drawn
  const root = `:root{${vars.map(([n, v]) => `${n}:${v.replace(/[;{}<>]/g, '')}`).join(';')}}`;
  const label = (n: string) => n.replace(/^--/, '').replace(/-/g, ' ');

  const colours = of('colour').map(([n, v]) => `<div class="swatch"><div class="chip-colour" style="background:var(${esc(n)})"></div><div class="meta">${copy(`var(${n})`, n)}<span class="val">${esc(v)}</span></div></div>`).join('');
  const weight = theme['--weight-heading'] ? `font-weight:var(--weight-heading);` : '';
  const tracking = theme['--tracking-heading'] ? `letter-spacing:var(--tracking-heading);` : '';
  const fonts = of('font').map(([n, v]) => `<div class="specimen"><span class="aa" style="font-family:var(${esc(n)});${n.includes('heading') ? weight + tracking : ''}">Aa Bb Gg 123</span><span style="font-family:var(${esc(n)})">The quick brown fox jumps over the lazy dog.</span>${copy(`var(${n})`, n)}<span class="val">${esc(v)}</span></div>`).join('');
  const sizes = of('size').map(([n, v]) => `<div class="size-row"><div class="row-meta">${copy(`var(${n})`, n)}<span class="val">${esc(v)}</span></div><div class="sample" style="font-size:var(${esc(n)});font-family:var(--font-heading, inherit)">${esc(label(n))}</div></div>`).join('');
  const lengths = of('length').map(([n, v]) => `<div class="bar-row"><div class="row-meta">${copy(`var(${n})`, n)}<span class="val">${esc(v)}</span></div>${n.startsWith('--radius')
    ? `<div class="radius" style="border-radius:min(var(${esc(n)}), 22px)"></div>`
    : `<div class="bar" style="width:var(${esc(n)})"></div>`}</div>`).join('');
  const other = of('other').map(([n, v]) => `<div class="bar-row"><div class="row-meta">${copy(`var(${n})`, n)}</div><span class="val">${esc(v)}</span></div>`).join('');

  const taskItem = (x: TaskNow) => `<li class="task${x.done ? ' done' : ''}"><span class="pin">${x.n}</span><span>${x.label ? `<span class="val">${esc(x.label)}${x.width ? ` · ${x.width} px` : ''}</span><br>` : x.width ? `<span class="val">${x.width} px</span><br>` : ''}${esc(x.text)}${x.done ? `<span class="reply">✓ ${esc(x.done.reply ?? 'Done')}${x.done.by === 'ai' ? ' (Kaity)' : ''}</span>` : ''}</span></li>`;
  const blocks = entries(ws).map((e) => `<li class="block" style="margin-left:${Math.min(e.depth, 6) * 18}px">
    <header><b>${esc(e.node.id)}</b><span class="kind">${esc(kindWord(e.node))}${typeOf(e.node) ? ` · type ${esc(typeOf(e.node)!)}` : ''}</span>${tagsOf(e.node).map((t) => `<span class="tag">#${esc(t)}</span>`).join('')}</header>
    <div class="chips">${copy(e.node.id)}${e.path !== e.node.id ? copy(e.path) : ''}${copy(`#sw-${e.node.id}`)}</div>
    ${e.words ? `<p class="words">${esc(e.words)}</p>` : ''}
    ${e.tasks.length ? `<ul class="tasks">${e.tasks.map(taskItem).join('')}</ul>` : ''}
  </li>`).join('');
  const open = tasks(ws, { open: true }).length;

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<base href="${esc(base)}">
<title>Handbook · ${esc(name)}</title>
<link rel="icon" type="image/svg+xml" href="/_tykerf/favicon.svg">
<style>
@font-face{font-family:'tykerf-plex-sans';src:url('/_tykerf/fonts/IBMPlexSans-Regular-Latin1.woff2') format('woff2');font-weight:400}
@font-face{font-family:'tykerf-plex-sans';src:url('/_tykerf/fonts/IBMPlexSans-Light-Latin1.woff2') format('woff2');font-weight:300}
@font-face{font-family:'tykerf-plex-sans';src:url('/_tykerf/fonts/IBMPlexSans-Medium-Latin1.woff2') format('woff2');font-weight:500}
@font-face{font-family:'tykerf-plex-sans';src:url('/_tykerf/fonts/IBMPlexSans-SemiBold-Latin1.woff2') format('woff2');font-weight:600}
@font-face{font-family:'tykerf-plex-mono';src:url('/_tykerf/fonts/IBMPlexMono-Regular-Latin1.woff2') format('woff2');font-weight:400}
@font-face{font-family:'tykerf-plex-mono';src:url('/_tykerf/fonts/IBMPlexMono-Medium-Latin1.woff2') format('woff2');font-weight:500}
${fontFaces(ws)}
${root}
${CSS}
</style></head>
<body class="hb">
<header class="top">${MARK}<b>tykerf</b><span class="page">handbook · ${esc(name)}</span><nav><a href="./">Back to the page</a><a href="_tykerf/handbook.md" download="handbook-${esc(name)}.md">Markdown</a></nav></header>
<main>
  <div><h1>${esc(name)}</h1><p class="lede">The page's system, generated from the page as it is now: its theme, and every block with what names it. Click a chip to copy it into a request for Kaity, any AI agent or a colleague. ${open ? `${open} ${open === 1 ? 'task is' : 'tasks are'} open.` : ''}</p></div>
  ${vars.length ? `<section class="card" id="theme"><h2>Theme</h2>
    ${colours ? `<h3>Colours</h3><div class="grid">${colours}</div>` : ''}
    ${fonts ? `<h3>Fonts</h3><div class="grid">${fonts}</div>` : ''}
    ${sizes ? `<h3>Text sizes</h3><div class="sizes">${sizes}</div>` : ''}
    ${lengths ? `<h3>Spacing, widths and corners</h3><div class="bars">${lengths}</div>` : ''}
    ${other ? `<h3>Other</h3><div class="bars">${other}</div>` : ''}
  </section>` : `<section class="card" id="theme"><h2>Theme</h2><p class="empty">This page has no theme: its boxes set their own colours and fonts.</p></section>`}
  <section class="card" id="blocks"><h2>Blocks</h2><ol class="blocks">${blocks}</ol></section>
</main>
<script>
document.addEventListener('click', async (e) => {
  const b = e.target.closest('[data-copy]');
  if (!b) return;
  try { await navigator.clipboard.writeText(b.dataset.copy); } catch { return; }
  b.classList.add('done');
  setTimeout(() => b.classList.remove('done'), 900);
});
</script>
</body></html>`;
}
